#!/usr/bin/env node
/**
 * Bakes what happened on each mission into `src/data/missionEvents.js`.
 *
 * Run with `npm run bake:mission-events`. Same rule as `bake-events.mjs`: not
 * one date here is transcribed from a mission timeline. Every one is read out
 * of the trajectory the app already draws — see `src/orbit/missionEvents.js` —
 * so clicking "Voyager 2 flies past Neptune" puts you at Neptune with Voyager 2
 * there, because the same samples produced both.
 *
 * ## Why bake this one
 *
 * Not for the reason the sky events are baked. This is a few hundred
 * milliseconds of work, not eight seconds — but it walks every sample of every
 * trajectory, and the trajectories are five megabytes of the bundle that the
 * app otherwise touches lazily. Doing it at build time keeps the cost off the
 * first frame entirely, and the result is 146 rows.
 *
 * ## The one thing that depends on when you run it
 *
 * A trajectory that stops in the past is a mission that ended; one that stops
 * in the future is a horizon. So `now` is stamped in, and a rebuild years from
 * now will correctly notice that missions still flying today have since ended.
 */

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

import { BODIES } from '../src/data/bodies.js'
import { julianDate } from '../src/orbit/kepler.js'
import { missionEventsFor } from '../src/orbit/missionEvents.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src/data/missionEvents.js')

const round = (n, places) => +n.toFixed(places)

function main() {
  const now = julianDate(new Date())
  const craft = BODIES.filter((b) => b.kind === 'spacecraft')

  const events = []
  for (const c of craft) events.push(...missionEventsFor(c, now))
  events.sort((a, b) => a.jd - b.jd)

  const rows = events
    .map((e) => {
      const parts = [`kind:'${e.kind}'`, `craft:'${e.craft}'`, `jd:${round(e.jd, 6)}`]
      if (e.body) parts.push(`body:'${e.body}'`)
      if (e.km !== undefined) parts.push(`km:${round(e.km, 1)}`)
      if (e.altitudeKm !== undefined) parts.push(`altitudeKm:${round(e.altitudeKm, 1)}`)
      if (e.resolutionKm !== undefined) parts.push(`resolutionKm:${round(e.resolutionKm, 1)}`)
      if (e.stayDays !== undefined) parts.push(`stayDays:${round(e.stayDays, 2)}`)
      if (e.lat !== undefined) parts.push(`lat:${round(e.lat, 4)},lon:${round(e.lon, 4)}`)
      return `  {${parts.join(',')}},`
    })
    .join('\n')

  const counts = {}
  for (const e of events) counts[e.kind] = (counts[e.kind] ?? 0) + 1

  writeFileSync(
    OUT,
    `/**
 * What happened on each mission — generated by \`scripts/bake-mission-events.mjs\`.
 *
 * Do not edit by hand. Every date is derived from the baked trajectories rather
 * than copied from a mission timeline: a flyby is a minimum of the distance to
 * a body, an arrival is the instant that body takes over the motion, and the
 * end of a mission is where JPL's ephemeris stops. See
 * \`src/orbit/missionEvents.js\` for what each kind does and does not claim.
 *
 * ${craft.length} craft, ${events.length} events: ${Object.entries(counts)
   .map(([k, n]) => `${n} ${k}`)
   .join(', ')}.
 *
 * \`altitudeKm\` is above the body's surface and \`resolutionKm\` is how far the
 * craft moves between samples at that encounter — the precision of the answer.
 * Where the second is large against the first, the first is a estimate: two
 * Earth gravity assists come out marginally inside the Earth.
 */

/**
 * @typedef {{
 *   kind: 'mission-begins' | 'flyby' | 'arrival' | 'landing' | 'mission-ends',
 *   craft: string,
 *   jd: number,
 *   body?: string,
 *   km?: number,
 *   altitudeKm?: number,
 *   resolutionKm?: number,
 *   stayDays?: number,
 *   lat?: number,
 *   lon?: number,
 * }} MissionEvent
 */

/** @type {MissionEvent[]} */
export const MISSION_EVENTS = [
${rows}
]

/** id → its own events, in time order. */
export const MISSION_EVENTS_BY_CRAFT = MISSION_EVENTS.reduce((map, e) => {
  ;(map[e.craft] ??= []).push(e)
  return map
}, {})
`,
  )

  console.log(
    `[mission events] ${events.length} across ${craft.length} craft — ${Object.entries(counts)
      .map(([k, n]) => `${n} ${k}`)
      .join(', ')}`,
  )
  console.log(`[mission events] wrote ${OUT}`)
}

main()
