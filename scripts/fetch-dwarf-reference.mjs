#!/usr/bin/env node
/**
 * Bakes JPL Horizons reference vectors for the dwarf planets.
 *
 * Writes `scripts/fixtures/dwarf-reference.js`, the fixture
 * `scripts/verify-bodies.mjs` checks against. Same idea as the planet fixture
 * that already sits beside it: the point of a verification is that it is
 * offline and deterministic, so the ground truth is fetched once, committed,
 * and never consulted again at test time.
 *
 * Run with `npm run fetch:reference`.
 */

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'scripts/fixtures/dwarf-reference.js')

/**
 * The trailing `;` marks a small-body designation. Without it Horizons reads
 * `1` as Mercury barycentre, which would silently produce a fixture of
 * entirely the wrong object.
 *
 * Pluto is `999`, the body rather than the `9` barycentre — Charon is massive
 * enough that the two differ by a couple of thousand kilometres.
 */
const BODIES = [
  { id: 'ceres', command: '1;' },
  { id: 'pluto', command: '999' },
  { id: 'haumea', command: '136108;' },
  { id: 'makemake', command: '136472;' },
  { id: 'eris', command: '136199;' },
]

/** Spread across the element table's window, including both edges. */
const DATES = ['1850-01-01', '1920-07-01', '1985-03-15', '2026-07-28', '2049-06-01']

async function vectorsFor(command, date) {
  const params = new URLSearchParams({
    format: 'text',
    COMMAND: command,
    OBJ_DATA: 'NO',
    MAKE_EPHEM: 'YES',
    EPHEM_TYPE: 'VECTORS',
    // The Sun's centre, matching the heliocentric frame kepler.js works in.
    CENTER: '500@10',
    REF_PLANE: 'ECLIPTIC',
    VEC_TABLE: '1',
    OUT_UNITS: 'AU-D',
    // Calendar dates have to arrive quoted or Horizons splits "2026-07-28
    // 00:00" on the space and reports no TLIST values at all.
    TLIST_TYPE: 'CAL',
    TLIST: `'${date} 00:00'`,
  })

  const res = await fetch(`https://ssd.jpl.nasa.gov/api/horizons.api?${params}`)
  if (!res.ok) throw new Error(`Horizons HTTP ${res.status}`)

  const text = await res.text()
  const block = text.split('$$SOE')[1]?.split('$$EOE')[0]
  if (!block) throw new Error(`no ephemeris block:\n${text.slice(-500)}`)

  const jd = Number(block.trim().split(' ')[0])
  const read = (key) => {
    const m = block.match(new RegExp(`${key}\\s*=\\s*(-?[\\d.]+E?[+-]?\\d*)`))
    if (!m) throw new Error(`missing ${key}`)
    return Number(m[1])
  }

  return { jd, x: read('X'), y: read('Y'), z: read('Z') }
}

async function main() {
  const rows = []
  for (const body of BODIES) {
    for (const date of DATES) {
      process.stdout.write(`[reference] ${body.id} @ ${date}… `)
      const v = await vectorsFor(body.command, date)
      rows.push({ body: body.id, date, ...v })
      console.log(`r=${Math.hypot(v.x, v.y, v.z).toFixed(4)} AU`)
    }
  }

  const body = rows
    .map(
      (r) =>
        `  { body: '${r.body}', date: '${r.date}', jd: ${r.jd}, ` +
        `x: ${r.x}, y: ${r.y}, z: ${r.z} },`,
    )
    .join('\n')

  writeFileSync(
    OUT,
    `/**
 * JPL Horizons heliocentric ecliptic vectors for the dwarf planets, in AU.
 *
 * GENERATED by \`scripts/fetch-dwarf-reference.mjs\` — rerun \`npm run
 * fetch:reference\` rather than editing. Generated ${new Date().toISOString().slice(0, 10)}.
 *
 * CENTER='500@10' (the Sun's centre), REF_PLANE='ECLIPTIC'. Pluto is body 999
 * rather than barycentre 9.
 */
export const DWARF_REFERENCE = [
${body}
]
`,
  )
  console.log(`[reference] wrote ${OUT}`)
}

main().catch((error) => {
  console.error(`[reference] ${error.message}`)
  process.exitCode = 1
})
