#!/usr/bin/env node
/**
 * Bakes published Galilean shadow-transit times, to check the app's against.
 *
 * Run with `npm run fetch:jupiter-shadows`. Writes
 * `scripts/fixtures/jupiter-shadows.js`, which is committed so `verify-bodies`
 * can use it offline.
 *
 * Source: Project Pluto's Jupiter satellite events table, generated with Guide
 * 9.1 (https://www.projectpluto.com/jevent.htm). Times are UT, and — this is the
 * part that matters — they are **as observed from Earth**, so they carry the
 * light time from Jupiter, which is around fifty minutes. Comparing raw
 * geometric times against them looks like a fifty-minute systematic error and is
 * really just the speed of light.
 *
 * ## Only the `Sha` rows
 *
 * The table interleaves four event types per satellite and two of them are easy
 * to confuse:
 *
 *   Sha   the moon's *shadow* crossing Jupiter's disc — a black dot on the
 *         cloud tops, which is what this app draws
 *   Tra   the *moon itself* crossing in front of Jupiter, a few minutes offset
 *         and lasting longer
 *
 * Reading a `Tra end` as a `Sha end` cost real time here: it made one Europa
 * transit look fifteen minutes wrong, with a duration that implied a chord
 * longer than Jupiter's diameter. That impossibility is what gave it away —
 * always sanity-check a disagreement against the geometry before believing it.
 * The two other codes, `Ecl` and `Occ`, are the moon disappearing rather than
 * anything falling on Jupiter.
 */

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'scripts/fixtures/jupiter-shadows.js')
const SOURCE = 'https://www.projectpluto.com/jevent.htm'

/** Roman numerals as the table writes them, in Galilean order. */
const MOONS = { I: 'io', II: 'europa', III: 'ganymede', IV: 'callisto' }

const MONTHS = {
  Jan: 0, Feb: 1, Mar: 2, Apr: 3, May: 4, Jun: 5,
  Jul: 6, Aug: 7, Sep: 8, Oct: 9, Nov: 10, Dec: 11,
}

async function main() {
  const res = await fetch(SOURCE)
  if (!res.ok) throw new Error(`HTTP ${res.status}`)

  const text = (await res.text()).replace(/<[^>]*>/g, '')
  const line = /^(I|II|III|IV)\s+Sha\s+(start|end)\s*:\s*(\d{4}) (\w{3}) (\d{2}) (\d{2}):(\d{2})/gm

  const rows = []
  for (const m of text.matchAll(line)) {
    const [, numeral, kind, year, month, day, hour, minute] = m
    const jd =
      Date.UTC(Number(year), MONTHS[month], Number(day), Number(hour), Number(minute)) /
        86400000 +
      2440587.5
    rows.push({ moon: MOONS[numeral], kind, jd, when: `${year}-${month}-${day} ${hour}:${minute}` })
  }

  if (rows.length < 100) throw new Error(`only ${rows.length} shadow events parsed`)

  const body = rows
    .map(
      (r) =>
        `  { moon: '${r.moon}', kind: '${r.kind}', when: '${r.when}', jd: ${r.jd.toFixed(6)} },`,
    )
    .join('\n')

  writeFileSync(
    OUT,
    `/**
 * Published shadow-transit contacts for the Galilean moons, ${rows[0].when.slice(0, 4)}.
 *
 * GENERATED by \`scripts/fetch-jupiter-shadows.mjs\` — rerun
 * \`npm run fetch:jupiter-shadows\` rather than editing. Generated ${new Date().toISOString().slice(0, 10)}.
 *
 * From Project Pluto's Jupiter satellite events table (Guide 9.1),
 * ${SOURCE}. Times are UT **as observed from Earth**, so
 * they include roughly fifty minutes of light time from Jupiter; anything
 * comparing against them has to add it.
 *
 * \`start\` and \`end\` are first and last contact of the shadow with Jupiter's
 * disc — the shadow's *edge*, not its axis, which is a couple of minutes either
 * side. Only \`Sha\` rows are here; the table's \`Tra\` rows are the moon itself
 * crossing the disc and are a different event.
 */
export const JUPITER_SHADOWS = [
${body}
]
`,
  )

  const counts = {}
  for (const r of rows) counts[r.moon] = (counts[r.moon] ?? 0) + 1
  console.log(`[jupiter-shadows] ${rows.length} contacts`, counts)
  console.log(`[jupiter-shadows] wrote ${OUT}`)
}

main().catch((error) => {
  console.error(`[jupiter-shadows] ${error.message}`)
  process.exitCode = 1
})
